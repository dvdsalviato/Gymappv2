List<String> _parole(String testo) => normalizzaNome(testo)
    .split(' ')
    .where((t) => t.isNotEmpty && !_paroleVuote.contains(t) && int.tryParse(t) == null)
    .map((t) => _sinonimi[t] ?? t)
    .toList();

class _VoceImmagine {
  final String base;
  final List<String> parole;
  final List<String> alias;
  const _VoceImmagine(this.base, this.parole, this.alias);
}

List<_VoceImmagine>? _indice;

List<_VoceImmagine> _voci() {
  return _indice ??= [
    for (final e in catalogoEsercizi)
      if (_immaginiCatalogo[e.nome] != null)
        _VoceImmagine(
          _immaginiCatalogo[e.nome]!,
          _parole(e.nome),
          _parole(aliasCatalogo[e.nome] ?? ''),
        ),
  ];
}

final Map<String, String?> _cache = {};

/// Nome base dell'immagine per un esercizio (anche con nome personalizzato:
/// "Lat machine", "Curl panca scott EZ"...). Null se non c'è niente di adatto.
String? immagineEsercizio(String nome) {
  if (_cache.containsKey(nome)) return _cache[nome];
  final risultato = _cerca(nome);
  _cache[nome] = risultato;
  return risultato;
}

